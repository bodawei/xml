import { ErrorCollector } from 'basic';
import { strOrBlank } from 'sToken';
import { CHARDATA_PTOKEN, ElementEndPToken, SPACE_PTOKEN } from 'token';

import { validityConstraint } from '../error/validityConstraint';
import { ValidityError } from '../error/ValidityError';
import { ElDeclType, ValidateState } from '../validateState';

const VID = validityConstraint.id;
const S_REGEXP = /^[\t\n\r ]*$/;

function elementEndValidate(el: ElementEndPToken, state: ValidateState, ec: ErrorCollector): void {
   const context = state.elementContext.activeContext;

   // if no context, then nothing to validate
   if (!context || state.elementContext.pastEnd) {
      return;
   }

   const declDetails = context.declDetails;

   if (declDetails.type !== ElDeclType.ELEMENT) {
      return;
   }

   const currentState = declDetails.graph.states[context.stateId];

   // §3.0.0 Validity Constraint: Element Valid
   //     2. The declaration matches children and the sequence of child elements
   //     belongs to the language generated by the regular expression in the content
   //     model, ...
   ec.check(
      !currentState.done,
      ValidityError.ID.ELEMENT_CONTENT_UNEXPECTED_END,
      [context.parentName, Object.keys(currentState.trans).join(', ')],
      el.name,
   );
}

export { elementEndValidate };
